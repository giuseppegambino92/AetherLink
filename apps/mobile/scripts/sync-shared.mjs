#!/usr/bin/env node
// Copies the desktop UI modules the mobile app reuses into apps/mobile/ui/shared/.
//
// The copies are GENERATED: never edit them — change apps/desktop/ui and re-run
// `npm run sync` (Tauri also runs this as `beforeBuildCommand`). Layout mirrors the
// desktop tree so relative imports keep working:
//
//   ui/shared/css/tokens.css
//   ui/shared/js/i18n.js              (one documented rewrite: locales live in ui/locales)
//   ui/shared/js/api.js               (generated shim → the mobile adapter ui/js/api.js)
//   ui/shared/js/lib/{spring,renderer,hid,format,icons,dom}.js
//   ui/shared/js/components/qr.js
//   ui/shared/vendor/{xterm,qrcode}/…
//
// `--check` exits 1 when a copy is missing or differs from what the sync would write
// (used by `npm run check`).
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const mobile = join(dirname(fileURLToPath(import.meta.url)), '..');
const desktopUi = join(mobile, '..', 'desktop', 'ui');
const out = join(mobile, 'ui', 'shared');
const checkOnly = process.argv.includes('--check');

const BANNER_JS = (src) => `// GENERATED by apps/mobile/scripts/sync-shared.mjs from apps/desktop/ui/${src} — do not edit.\n`;
const BANNER_CSS = (src) => `/* GENERATED by apps/mobile/scripts/sync-shared.mjs from apps/desktop/ui/${src} — do not edit. */\n`;

/** [source (relative to apps/desktop/ui), destination (relative to ui/shared), rewrite?] */
const FILES = [
  ['css/tokens.css', 'css/tokens.css'],
  [
    'js/i18n.js',
    'js/i18n.js',
    // The mobile app keeps its own locale tables in apps/mobile/ui/locales/.
    (s) => replaceOnce(s, '`../locales/${code}.json`', '`../../locales/${code}.json`'),
  ],
  ['js/lib/spring.js', 'js/lib/spring.js'],
  ['js/lib/renderer.js', 'js/lib/renderer.js'],
  ['js/lib/hid.js', 'js/lib/hid.js'],
  ['js/lib/format.js', 'js/lib/format.js'],
  ['js/lib/icons.js', 'js/lib/icons.js'],
  ['js/lib/dom.js', 'js/lib/dom.js'],
  ['js/components/qr.js', 'js/components/qr.js'],
  ['vendor/xterm/xterm.mjs', 'vendor/xterm/xterm.mjs', null, 'raw'],
  ['vendor/xterm/addon-fit.mjs', 'vendor/xterm/addon-fit.mjs', null, 'raw'],
  ['vendor/xterm/xterm.css', 'vendor/xterm/xterm.css', null, 'raw'],
  ['vendor/xterm/LICENSE', 'vendor/xterm/LICENSE', null, 'raw'],
  ['vendor/qrcode/qrcode.mjs', 'vendor/qrcode/qrcode.mjs', null, 'raw'],
  ['vendor/qrcode/LICENSE', 'vendor/qrcode/LICENSE', null, 'raw'],
];

// The shared renderer imports `camelize` from '../api.js'; route it to the mobile adapter.
const MOBILE_API = ['..', '..', 'js', 'api.js'].join('/');
const GENERATED = [
  [
    'js/api.js',
    '// GENERATED by apps/mobile/scripts/sync-shared.mjs — do not edit.\n' +
      '// Shared desktop modules import "../api.js"; on mobile that is the mobile adapter.\n' +
      `export * from '${MOBILE_API}';\n`,
  ],
];

function replaceOnce(s, from, to) {
  const i = s.indexOf(from);
  if (i < 0 || s.indexOf(from, i + 1) >= 0) {
    console.error(`sync-shared: expected exactly one "${from}" in the desktop source — update the rewrite rule`);
    process.exit(1);
  }
  return s.slice(0, i) + to + s.slice(i + from.length);
}

const expected = new Map();
for (const [src, dest, rewrite, mode] of FILES) {
  const from = join(desktopUi, src);
  if (!existsSync(from)) {
    console.error(`sync-shared: missing ${relative(mobile, from)} (run \`npm install\` in apps/desktop for vendor files)`);
    process.exit(1);
  }
  let body = readFileSync(from, mode === 'raw' ? undefined : 'utf8');
  if (mode !== 'raw') {
    if (rewrite) body = rewrite(body);
    body = (dest.endsWith('.css') ? BANNER_CSS(src) : BANNER_JS(src)) + body;
  }
  expected.set(dest, body);
}
for (const [dest, body] of GENERATED) expected.set(dest, body);

let stale = 0;
for (const [dest, body] of expected) {
  const p = join(out, dest);
  const same = existsSync(p) && Buffer.compare(readFileSync(p), Buffer.from(body)) === 0;
  if (same) continue;
  if (checkOnly) {
    stale++;
    console.error(`sync-shared: ui/shared/${dest} is missing or out of date — run \`npm run sync\``);
    continue;
  }
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, body);
  console.log(`sync-shared: apps/desktop/ui → ui/shared/${dest}`);
}
if (checkOnly) {
  if (stale) process.exit(1);
  console.log(`sync-shared: OK — ${expected.size} shared files up to date.`);
} else {
  writeFileSync(join(out, 'README.md'), '# Generated\n\nCopied from `apps/desktop/ui` by `apps/mobile/scripts/sync-shared.mjs`. Do not edit; run `npm run sync`.\n');
  console.log(`sync-shared: ${expected.size} files in sync.`);
}
